#!/usr/bin/env python3
"""Generate bounded houji HFI tables from this phone's captured AOP and FDT.

Reads local files only. Embedded ARC variants must agree. This is not a live
command-DB read or evidence that a voltage/frequency request was executed.
"""
from pathlib import Path
import hashlib
import json
import re
import struct

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = Path('${HOUJI_ARTIFACTS}')


def tables(aop, dts):
    assert hashlib.sha256(aop).hexdigest() == 'c572b184827e4a6fac8f87318da81b36e0e8056d87025ac8ae40e764d4129f8c'
    variants = []
    for base in (0x1e1c0, 0x1eb70):
        rails = {}
        for index in range(28):
            name, _, _, address, size, offset = struct.unpack_from('<8sIIIHH', aop, base + 24 * index)
            name = name.rstrip(b'\0').decode()
            if name not in ('cx.lvl', 'mx.lvl', 'gfx.lvl'):
                continue
            assert size == 32 and address == {'cx.lvl': 0x30000, 'mx.lvl': 0x30010, 'gfx.lvl': 0x30050}[name]
            values = list(struct.unpack_from('<16H', aop, base - 0x1c0 + offset))
            while values[-1] == 0:
                values.pop()
            assert values[0] == 0 and values == sorted(set(values))
            rails[name] = values
        assert len(rails) == 3
        variants.append(rails)
    assert variants[0] == variants[1]
    rails = variants[0]

    def vote(name, level):
        index = next(i for i, value in enumerate(rails[name]) if value >= level)
        mx = next(i for i, value in enumerate(rails['mx.lvl']) if value >= rails[name][index])
        return (rails[name][index] << 16) | (mx << 8) | index

    # Lowest GPU point is shared by every captured speed bin. No higher GPU
    # rate is advertised by this diagnostic table; CORE/START cannot select it.
    points = re.findall(r'qcom,level = <0x([0-9a-f]+)>;\s*qcom,gpu-freq = <0x([0-9a-f]+)>;', dts)
    points = [(int(level, 16), int(rate, 16)) for level, rate in points]
    assert min(rate for _, rate in points) == 231000000
    assert all(level == 52 for level, rate in points if rate == 231000000)
    assert 'qcom,gmu-freq-table = <0xf7f4900 0x40 0x2540be40 0x80>' in dts
    perf = [0, 1, 2, 3, 0, 0xffffffff, 0, vote('gfx.lvl', 52), 0xffffffff, 231000,
            3, 2, 0, 0, vote('cx.lvl', 64), 260000, vote('cx.lvl', 128), 625000]
    bcm = {}
    for index in range(31):
        name, _, _, address, size, offset = struct.unpack_from('<8sIIIHH', aop, 0x1e6c8 + 24 * index)
        name = name.rstrip(b'\0').decode()
        assert size == 8 and offset == index * 8
        if name in ('SH0', 'MC0', 'ACV', 'CN0'):
            unit, width, vcd, reserved = struct.unpack_from('<IHBB', aop, 0x1e5d0 + offset)
            assert unit and not reserved
            bcm[name] = dict(address=address, unit=unit, width=width, vcd=vcd)
    assert set(bcm) == {'SH0', 'MC0', 'ACV', 'CN0'}
    levels = [int(value, 16) for value in re.search(r'qcom,bus-table-ddr = <([^>]+)>', dts)[1].split()]
    assert len(levels) == 10 and levels[0] == 0 and levels == sorted(set(levels))

    def command(commit, valid, x, y):
        return (int(commit) << 30) | (int(valid) << 29) | (min(x, 0x3fff) << 14) | min(y, 0x3fff)

    bw = [len(levels), 1, 3, 1, 7, bcm['CN0']['address']] + [0] * 5
    for level in (0, 100):
        value = level * bcm['CN0']['width'] // 4 * 1000 // bcm['CN0']['unit']
        value = max(value, 1) if level else 0
        bw += [command(True, bool(value), value, value)] + [0] * 5
    bw += [bcm[name]['address'] for name in ('SH0', 'MC0', 'ACV')] + [0] * 5
    for level in levels + [0] * (16 - len(levels)):
        values = []
        for name, width in (('SH0', 16), ('MC0', 4), ('ACV', 0)):
            if name == 'ACV':
                values.append(command(True, bool(level), 0, 4 if level >= 2736 * 1000 * 4 else 0))
            else:
                value = level * bcm[name]['width'] // width * 1000 // bcm[name]['unit']
                value = max(value, 1) if level else 0
                values.append(command(True, bool(value), value, value))
        bw += values + [0] * 5
    assert len(perf) == 18 and len(bw) == 159
    return perf, bw, dict(rails=rails, bcm=bcm, ddr_levels=levels, gpu_frequency_khz=231000,
                          live_command_db_verified=False, higher_GPU_rates_advertised=False)


def main():
    aop_path = ARTIFACTS / 'native-research/houji-aop-20261025/aop_a.bin'
    dts_path = ARTIFACTS / 'native-port/device-baseline/live-fdt.dts'
    perf, bw, metadata = tables(aop_path.read_bytes(), dts_path.read_text())
    lines = ['/* SPDX-License-Identifier: BSD-2-Clause-Patent',
             ' * Generated by scripts/make-gpu-hfi-tables.py from own houji AOP/FDT.',
             ' * Wire format follows fixed OnePlus 453d8875 adreno_hfi.h.',
             ' * Not a live command-DB or frequency measurement. */',
             '#ifndef HOUJI_GPU_HFI_TABLES_H', '#define HOUJI_GPU_HFI_TABLES_H', '#include <stdint.h>']
    for name, values in (('hhb_perf', perf), ('hhb_bw', bw)):
        lines.append(f'static const uint32_t {name}[{len(values)}]={{')
        lines.extend(' '+','.join(f'0x{value:08x}u' for value in values[start:start + 6]) + ','
                     for start in range(0, len(values), 6))
        lines.append('};')
    lines.append('#endif')
    output = ROOT / 'native/gpu/uefi/GpuHfiTables.h'
    output.write_text('\n'.join(lines) + '\n')
    metadata.update(aop_sha256=hashlib.sha256(aop_path.read_bytes()).hexdigest(),
                    dts_sha256=hashlib.sha256(dts_path.read_bytes()).hexdigest(),
                    table_header_sha256=hashlib.sha256(output.read_bytes()).hexdigest(),
                    source='OnePlus 453d8875 HFI wire + Ace5 aaa100d1 table algorithm; own AOP offsets/DT',
                    perf_payload=perf, bandwidth_payload=bw)
    (ROOT / 'native/gpu/hfi-tables.json').write_text(json.dumps(metadata, indent=2) + '\n')
    print('Generated own-device HFI tables: 18 + 159 payload words; GPU limited to 231 MHz')


if __name__ == '__main__':
    main()
