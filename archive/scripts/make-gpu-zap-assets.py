#!/usr/bin/env python3
"""Bind the already captured, signed houji gen70900 ZAP to bounded C assets.

No phone access, firmware edits, signing, loading, or authentication. A different
binary is refused even if it has a superficially compatible ELF layout.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA = "ab6035deaf3df20b52f1fc0b27b10f2ad392398e2eb802b68746d5511981931e"
METADATA_SHA = "29096ea050fd2b44032fc5fe7bea148a1427e1443694d34e318160ad839cdb1a"
SEGMENT_SHA = "bb8e56248f7ae112e8df6a1a365afe616ab24f9faf330b4b94115b3d7efa998f"
RESERVATION_BASE = 0x9B09A000
RESERVATION_BYTES = 0x2000


def decode(blob):
    if len(blob) != 12088 or hashlib.sha256(blob).hexdigest() != SOURCE_SHA:
        raise ValueError("not the exact captured, signed houji gen70900_zap.mbn")
    if blob[:7] != b"\x7fELF\x01\x01\x01":
        raise ValueError("requires the source-bound ELF32 little-endian image")
    if struct.unpack_from("<H", blob, 18)[0] != 164:
        raise ValueError("unexpected ELF machine")
    phoff = struct.unpack_from("<I", blob, 28)[0]
    ehsize, phent, phnum = struct.unpack_from("<HHH", blob, 40)
    if (phoff, ehsize, phent, phnum) != (52, 52, 32, 3):
        raise ValueError("unexpected source-bound ELF header layout")
    headers = [struct.unpack_from("<8I", blob, phoff + phent * i) for i in range(phnum)]
    expected = [
        (0, 0, 0, 0, 148, 0, 0x07000000, 0),
        (1, 0x1000, 0x1000, 0x1000, 1072, 1072, 0x08000007, 0x100000),
        (0, 0x2000, 0, 0, 3896, 3896, 0x02000000, 0x1000),
    ]
    if headers != expected:
        raise ValueError("program headers differ from the audited OEM image")
    metadata = blob[:headers[0][4]] + blob[0x2000:0x2000 + 3896]
    segment = blob[0x1000:0x1000 + 1072]
    if len(metadata) != 4044 or hashlib.sha256(metadata).hexdigest() != METADATA_SHA:
        raise ValueError("metadata binding failed")
    if len(segment) != 1072 or hashlib.sha256(segment).hexdigest() != SEGMENT_SHA:
        raise ValueError("loadable segment binding failed")
    return metadata, segment, headers


def c_array(name, data):
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for at in range(0, len(data), 16):
        lines.append(" " + ",".join(f"0x{x:02x}" for x in data[at:at + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def render(source, blob):
    metadata, segment, headers = decode(blob)
    header = "\n".join([
        "/* Generated by scripts/make-gpu-zap-assets.py from this phone's signed OEM image.",
        " * Firmware bytes retain their original ownership; no firmware is modified or signed.",
        " * Source/segment hashes and exact relocation plan are in zap-assets-source.json. */",
        "#ifndef HOUJI_GPU_ZAP_ASSETS_H", "#define HOUJI_GPU_ZAP_ASSETS_H", "#include <stdint.h>",
        "#define HOUJI_ZAP_META_BYTES 4044u", "#define HOUJI_ZAP_SEGMENT_BYTES 1072u",
        f'#define HOUJI_ZAP_SOURCE_SHA256 "{SOURCE_SHA}"',
        f'#define HOUJI_ZAP_METADATA_SHA256 "{METADATA_SHA}"',
        f'#define HOUJI_ZAP_SEGMENT_SHA256 "{SEGMENT_SHA}"',
        c_array("mHoujiZapMetadata", metadata), c_array("mHoujiZapSegment", segment),
        "#endif", "",
    ])
    manifest = {
        "status": "source-bound data only; not loaded or authenticated",
        "generator": "scripts/make-gpu-zap-assets.py", "source": str(source.resolve()),
        "source_bytes": len(blob), "source_sha256": SOURCE_SHA,
        "metadata": {"bytes": len(metadata), "sha256": METADATA_SHA,
                     "crc32_ieee": f"{zlib.crc32(metadata):08x}",
                     "layout": "ELF header/program-header bytes [0,148) + hash bytes [8192,12088)"},
        "segment": {"bytes": len(segment), "sha256": SEGMENT_SHA,
                    "crc32_ieee": f"{zlib.crc32(segment):08x}", "file_offset": 4096,
                    "relocated_destination": RESERVATION_BASE, "bss_bytes": 0},
        "reservation": {"base": RESERVATION_BASE, "bytes": RESERVATION_BYTES,
                        "load_span": 4096, "pas_id": 13, "relocatable": True},
        "program_headers": [dict(zip(
            ["type", "offset", "vaddr", "paddr", "filesz", "memsz", "flags", "align"], h))
            for h in headers],
        "header_sha256": hashlib.sha256(header.encode()).hexdigest(),
        "source_plan": "native/gpu/zap-load-source-plan.json",
        "runtime_writes_or_calls": False,
    }
    return header, json.dumps(manifest, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output-header", type=Path,
                        default=ROOT / "native/gpu/uefi/GpuZapAssets.h")
    parser.add_argument("--output-manifest", type=Path,
                        default=ROOT / "native/gpu/zap-assets-source.json")
    args = parser.parse_args()
    if args.output_header.resolve() == args.output_manifest.resolve():
        parser.error("header and manifest must be different files")
    if args.source.resolve() in (args.output_header.resolve(), args.output_manifest.resolve()):
        parser.error("never overwrite the signed source firmware")
    try:
        header, manifest = render(args.source, args.source.read_bytes())
    except (OSError, ValueError, struct.error) as error:
        parser.error(str(error))
    # Validation and both complete outputs are ready before any output mutation.
    for path in (args.output_header, args.output_manifest):
        if not path.parent.is_dir() or (path.exists() and not path.is_file()):
            parser.error(f"output requires an existing directory and regular-file path: {path}")
    args.output_header.write_text(header)
    args.output_manifest.write_text(manifest)
    print("Bound signed houji ZAP: metadata=4044 segment=1072 reserved-span=4096; no load/auth")


if __name__ == "__main__":
    main()
