#!/usr/bin/env python3
"""Create an explicit houji ClockDxe diagnostic copy with resumable BRK sites.

Only selected BL, BLR X8 and CBZ/CBNZ W0 instructions change. The exception
callback must execute their original control-flow semantics. No failure path,
hardware access, DEPEX or initialization function is removed.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

SOURCE_SHA = 'f498e08bf978b36af750a3958c83b788d39f786069d31d6483d4df66d4ce69ba'
BRK_IMMEDIATE = 0x484A
BRK_OPCODE = 0xD4200000 | (BRK_IMMEDIATE << 5)
CALLS = (
    ('DriverInit', 0x7D80, True),
    ('InitBases', 0x7B88, True),
    ('HWIO.Map', 0x3CDC, True),
    ('HALSetup', 0x7C78, False),
    ('InternalAttach', 0x7C90, True),
    ('InitSourcesSoft', 0x7CB8, True),
    ('InitVoltage', 0x7CE4, True),
    ('InitDFSDomains', 0x7D20, True),
    ('InitCESTA', 0x7D3C, True),
    ('InitTarget', 0x7D50, True),
    ('InitNPA', 0x7D64, True),
    ('PostInit_824c', 0x7DC0, True),
    ('CESTA.PrepareClocks', 0xA730, True),
    ('CESTA.LookupClock', 0xA620, True),
    ('CESTA.EnableClock', 0xA634, True),
    ('CESTA.Program', 0xA768, True),
    ('CESTA.IsPowerOn', 0xA7A8, False),
    ('CESTA.PreparePower', 0xA7C4, True),
    ('CESTA.EnablePower', 0xA7DC, True),
    ('CESTA.ReleaseClocks', 0xA810, True),
    ('CESTA.LookupRelease', 0xA6B4, True),
    ('CESTA.DisableClock', 0xA6C8, False),
    ('CESTA.RailVoltage', 0xA518, False),
    ('CESTA.CmdDbAddress', 0xA52C, True),
    ('Clock.SyncEnter', 0x5260, False),
    ('Clock.SyncLeave', 0x52F0, False),
    ('Clock.DomainEnable', 0x5328, True),
    ('Clock.HALEnable', 0x534C, False),
    ('Clock.HALSupports', 0x5390, False),
    ('Clock.HALIsOn', 0x53A0, False),
    ('Clock.PollDelay', 0x53B4, False),
    ('Clock.PollRead', 0x53BC, False),
    ('Clock.PreparePower', 0x4EDC, True),
    ('Clock.SelectSource', 0x4F18, True),
)


def create(source):
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA:
        raise ValueError('Clock source differs from the unmodified device PE')
    pe = struct.unpack_from('<I', source, 0x3C)[0]
    assert source[pe:pe+4] == b'PE\0\0'
    machine, sections = struct.unpack_from('<HH', source, pe+4)
    assert machine == 0xAA64
    section_table = pe + 24 + struct.unpack_from('<H', source, pe+20)[0]
    text = source[section_table:section_table+40]
    assert text[:8].rstrip(b'\0') == b'.text'
    _, rva, raw_size, raw = struct.unpack_from('<IIII', text, 8)
    assert rva == raw == 0x1000 and raw_size >= 0xD000
    patched = bytearray(source)
    sites = []
    for name, call, has_return in CALLS:
        for is_return in range(2 if has_return else 1):
            offset = call + 4 * is_return
            opcode = struct.unpack_from('<I', source, offset)[0]
            if is_return:
                assert opcode & 0x7E00001F == 0x34000000, (name, hex(opcode))
            else:
                assert opcode & 0xFC000000 == 0x94000000 or opcode == 0xD63F0100
            struct.pack_into('<I', patched, offset, BRK_OPCODE)
            sites.append({'name': name, 'rva': offset, 'opcode': opcode,
                          'is_return': bool(is_return)})
    allowed = {s['rva'] + byte for s in sites for byte in range(4)}
    assert all(a == b or i in allowed for i, (a, b) in enumerate(zip(source, patched)))
    header = '''/* Generated by patch-clock-trace.py from pinned original ClockDxe.
 * Diagnostic BRKs preserve every original call and conditional branch.
 */
#define HOUJI_CLOCK_TRACE_BRK 0x%08XU
#define HOUJI_CLOCK_TRACE_ISS 0x%04XU
typedef struct { UINT32 Rva, Opcode; BOOLEAN IsReturn; CONST CHAR8 *Name; } CLOCK_TRACE_SITE;
STATIC CONST CLOCK_TRACE_SITE mClockTraceSites[] = {
''' % (BRK_OPCODE, BRK_IMMEDIATE)
    for s in sites:
        header += '  {0x%05X, 0x%08X, %s, "%s"},\n' % (
            s['rva'], s['opcode'], 'TRUE' if s['is_return'] else 'FALSE', s['name'])
    header += '};\n'
    return bytes(patched), sites, header


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--header', type=Path, required=True)
    a = p.parse_args()
    if a.output.exists():
        raise FileExistsError(a.output)
    source = a.source.read_bytes()
    patched, sites, header = create(source)
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_bytes(patched)
    a.header.write_text(header)
    a.output.with_suffix('.json').write_text(json.dumps({
        'source': str(a.source), 'source_sha256': SOURCE_SHA,
        'diagnostic_sha256': hashlib.sha256(patched).hexdigest(),
        'bytes': len(patched), 'patched': True, 'mode': 'resumable-stage-trace',
        'brk_opcode': hex(BRK_OPCODE), 'sites': sites,
        'original_calls_and_conditions_preserved_by_handler': True,
        'hardware_tested': False,
    }, indent=2) + '\n')
    print(f'Created diagnostic copy: {len(sites)} checked trace sites')


if __name__ == '__main__':
    main()
