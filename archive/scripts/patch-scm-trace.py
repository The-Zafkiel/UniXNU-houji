#!/usr/bin/env python3
"""Create a pinned SCM diagnostic copy; no original call or memory opcode changes.

Nine MOV/ADRP instructions become BRK. The firmware handler must reproduce only
their exact register result and advance ELR by four. The raw PE stays intact.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

SOURCE_SHA = '10015c434b2d7e4cfc62d39eb35e80f5b1073baa51b6780aaa2536aa5006ec0a'
IMAGE_BYTES = 0xD000
BRK_IMMEDIATE = 0x4853
BRK_OPCODE = 0xD4200000 | (BRK_IMMEDIATE << 5)
# name, RVA, original opcode, destination register, value kind, sample kind
# sample: 0 entry, 1 stack request, 2 pointer return, 3 pending X8 size,
# 4 before SmcInvoke, 5 EFI_STATUS return, 6 inside ClientEnv.
SITES = (
    ('SharedInitEntered', 0x1E2C, 0x52800709, 9, 0, 0),
    ('Allocate56Begin', 0x1E84, 0x52800042, 2, 0, 1),
    ('Allocate56End', 0x1E9C, 0xD0000056, 22, 1, 2),
    ('Allocate8192Begin', 0x1EB4, 0x52800042, 2, 0, 3),
    ('Allocate8192End', 0x1EC4, 0xD0000048, 8, 1, 2),
    ('SmcInvokeBegin', 0x1ED0, 0xD0000048, 8, 1, 4),
    ('SmcInvokeEnd', 0x1EE0, 0xAA0003F3, 19, 2, 5),
    ('ClientEnvBegin', 0x4D38, 0xF0000033, 19, 1, 6),
    ('ClientEnvEnd', 0x1EEC, 0xAA0003F3, 19, 2, 5),
)
# Real calls bordering the observations. These bytes must never be patched.
CALLS = {0x150C: 0x94000240, 0x1E98: 0xD63F0100,
         0x1EC0: 0xD63F0120, 0x1EDC: 0x94000529,
         0x1EE8: 0x94000B90}


def header():
    text = '''/* Generated by patch-scm-trace.py from the pinned raw houji SCM PE.
 * Only exact MOV/ADRP semantics. No memory, call, branch or SMC emulation.
 */
#define HOUJI_SCM_TRACE_BRK 0x%08XU
#define HOUJI_SCM_TRACE_ISS 0x%04XU
#define HOUJI_SCM_TRACE_BYTES 0x%XU
typedef struct {
  UINT32 Rva, Opcode, Register, Kind, Sample;
  CONST CHAR8 *Name;
} SCM_TRACE_SITE;
STATIC CONST SCM_TRACE_SITE mScmTraceSites[] = {
''' % (BRK_OPCODE, BRK_IMMEDIATE, IMAGE_BYTES)
    for name, rva, opcode, register, kind, sample in SITES:
        text += '  {0x%X, 0x%08X, %u, %u, %u, "%s"},\n' % (
            rva, opcode, register, kind, sample, name)
    text += '''};

STATIC BOOLEAN
ScmTraceOriginalValue (UINTN Index, UINT64 Base, UINT64 Pc, UINT64 X0, UINT64 *Value)
{
  if (!Value || Index >= sizeof (mScmTraceSites) / sizeof (mScmTraceSites[0]) ||
      (Base & 4095) || Base > MAX_UINT64 - HOUJI_SCM_TRACE_BYTES) { return FALSE; }
  CONST SCM_TRACE_SITE *Site = &mScmTraceSites[Index];
  if (Pc != Base + Site->Rva) { return FALSE; }
  UINT64 Result;
  if (Site->Kind == 0 && (Site->Opcode == 0x52800709U || Site->Opcode == 0x52800042U)) {
    Result = (Site->Opcode >> 5) & 0xFFFFU; // MOV Wn: zero extend to Xn.
  } else if (Site->Kind == 1 &&
      (Site->Opcode == 0xD0000056U || Site->Opcode == 0xD0000048U || Site->Opcode == 0xF0000033U)) {
    INT64 Delta = (INT64)(((Site->Opcode >> 5) & 0x7FFFFU) << 2) |
      (INT64)((Site->Opcode >> 29) & 3U);
    if (Delta & 0x100000) { Delta -= 0x200000; }
    Result = (Pc & ~4095ULL) + (UINT64)(Delta * 4096);
    if (Result != Base + 0xB000) { return FALSE; }
  } else if (Site->Kind == 2 && Site->Opcode == 0xAA0003F3U) {
    Result = X0; // MOV X19,X0; NZCV, SP and LR are unchanged.
  } else { return FALSE; }
  *Value = Result;
  return TRUE;
}
'''
    return text


def create(source):
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA:
        raise ValueError('SCM source differs from the pinned raw phone PE')
    pe = struct.unpack_from('<I', source, 0x3C)[0]
    if source[pe:pe + 4] != b'PE\0\0' or struct.unpack_from('<H', source, pe + 4)[0] != 0xAA64:
        raise ValueError('Expected AArch64 PE')
    if len(source) != IMAGE_BYTES:
        raise ValueError('Unexpected raw SCM image size')
    table = pe + 24 + struct.unpack_from('<H', source, pe + 20)[0]
    text = source[table:table + 40]
    _, rva, raw_size, raw = struct.unpack_from('<IIII', text, 8)
    if text[:8].rstrip(b'\0') != b'.text' or rva != 0x1000 or raw != rva or raw_size != 0xA000:
        raise ValueError('Unexpected executable section layout')
    for offset, opcode in CALLS.items():
        if struct.unpack_from('<I', source, offset)[0] != opcode:
            raise ValueError('Original SCM call differs')
    patched = bytearray(source)
    records = []
    for index, (name, offset, opcode, register, kind, sample) in enumerate(SITES):
        if not 0x1000 <= offset <= 0xAFFC or struct.unpack_from('<I', source, offset)[0] != opcode:
            raise ValueError('SCM observation instruction differs: ' + name)
        struct.pack_into('<I', patched, offset, BRK_OPCODE)
        records.append(dict(name=name, rva=offset, opcode=opcode, register=register,
                            kind=kind, sample=sample, step=0x8000 + index))
    allowed = {record['rva'] + n for record in records for n in range(4)}
    if any(a != b and i not in allowed for i, (a, b) in enumerate(zip(source, patched))):
        raise AssertionError('Unexpected byte changed')
    return bytes(patched), records, header()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--header', type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists() or args.output.resolve() == args.source.resolve():
        raise FileExistsError(args.output)
    source = args.source.read_bytes()
    diagnostic, sites, generated = create(source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(diagnostic)
    args.header.write_text(generated)
    args.output.with_suffix('.json').write_text(json.dumps(dict(
        source=str(args.source), source_sha256=SOURCE_SHA,
        diagnostic_sha256=hashlib.sha256(diagnostic).hexdigest(), bytes=len(diagnostic),
        patched=True, mode='exact-mov-adrp-observation', brk_opcode=hex(BRK_OPCODE),
        sites=sites, original_calls_memory_branches_smc_unchanged=True,
        hardware_tested=False), indent=2) + '\n')
    print(f'Created {len(sites)}-site SCM diagnostic copy: {args.output}')


if __name__ == '__main__':
    main()
